def can_recruit(
    state: WorldState,
    recruiter_id: str,
    target_id: str,
    agent_specs: dict[str, AgentSpec],
) -> tuple[bool, str]:
    """
    Check if a recruitment attempt makes sense.

    Returns (can_recruit, reason).
    """
    recruiter_spec = agent_specs.get(recruiter_id)
    target_spec = agent_specs.get(target_id)

    if not recruiter_spec or not target_spec:
        return False, "Agent not found"

    # Must be a rebel to recruit
    if recruiter_spec.true_faction != Faction.REBEL:
        return False, "Only rebels can recruit"

    # Can't recruit guards
    if target_spec.public_role.value == "guard":
        return False, "Cannot recruit guards"

    # Check if already recruited
    target_state = state.get_agent(target_id)
    if target_state and target_state.is_recruited:
        return False, "Already recruited"

    # Check trust level
    trust = state.get_trust(target_id, recruiter_id)
    if trust < 0.3:
        return False, f"Insufficient trust ({trust:.2f})"

    return True, "Can attempt recruitment"


def estimate_recruitment_success(
    state: WorldState,
    recruiter_id: str,
    target_id: str,
    agent_specs: dict[str, AgentSpec],
) -> float:
    """
    Estimate probability of recruitment success.

    Based on:
    - Trust level
    - Target's traits (loyalty, courage)
    - Circumstances (location, time, witnesses)
    """
    target_spec = agent_specs.get(target_id)
    if not target_spec:
        return 0.0

    target_state = state.get_agent(target_id)
    if not target_state:
        return 0.0

    # Base probability from trust
    trust = state.get_trust(target_id, recruiter_id)
    base_prob = max(0, (trust - 0.3) / 0.7)  # 0 at trust=0.3, 1 at trust=1.0

    # Modify by target's traits
    from ..core.types import TraitName
    loyalty_to_authority = target_spec.rl_profile.get_trait(TraitName.LOYALTY, 0.5)
    courage = target_spec.rl_profile.get_trait(TraitName.COURAGE, 0.5)

    # High loyalty to authority = harder to recruit
    # High courage = more likely to take the risk
    trait_modifier = (1 - loyalty_to_authority * 0.5) * (0.5 + courage * 0.5)

    # Location modifier (tavern at night is safest)
    location_mod = 1.0
    if target_state.location == Location.TAVERN and state.time_of_day == TimeOfDay.NIGHT:
        location_mod = 1.3
    elif target_state.location in {Location.MARKET, Location.TOWN_SQUARE}:
        location_mod = 0.7  # Too public

    # Witness modifier
    witnesses = len(state.get_nearby_agents(target_id)) - 1  # Exclude recruiter
    witness_mod = max(0.3, 1 - witnesses * 0.15)

    final_prob = base_prob * trait_modifier * location_mod * witness_mod
    return min(1.0, max(0.0, final_prob))
